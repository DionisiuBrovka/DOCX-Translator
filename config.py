"""
Конфигурация приложения DOCX Translator.

Все настройки читаются из переменных окружения с разумными значениями
по умолчанию. Также создаются рабочие директории для загрузок и результатов.
"""

import os
import logging
from pathlib import Path

# ---------------------------------------------------------------------------
# Директории для файлов
# ---------------------------------------------------------------------------

# Папка для временного хранения загруженных .docx файлов.
# Файлы удаляются сразу после обработки.
UPLOAD_FOLDER = Path("uploads")

# Папка для готовых переведённых документов.
# Файлы остаются до перезапуска сервера (хранение in-memory).
OUTPUT_FOLDER = Path("outputs")

# Создаём директории при импорте, если их ещё нет
UPLOAD_FOLDER.mkdir(exist_ok=True)
OUTPUT_FOLDER.mkdir(exist_ok=True)

# ---------------------------------------------------------------------------
# Groq API
# ---------------------------------------------------------------------------

# Ключ для доступа к Groq API. Можно задать через окружение или ввести
# через веб-интерфейс при каждом переводе.
GROQ_API_KEY = os.environ.get("GROQ_API_KEY", "")

# Модель LLM для перевода. Llama 3.3 70B — основной выбор: хорошее качество
# перевода и высокая скорость на инфраструктуре Groq.
GROQ_MODEL = os.environ.get("GROQ_MODEL", "llama-3.3-70b-versatile")

# ---------------------------------------------------------------------------
# Flask
# ---------------------------------------------------------------------------

# Секретный ключ для подписи сессионных cookie Flask.
# В продакшене ОБЯЗАТЕЛЬНО заменить на случайную строку.
SECRET_KEY = os.environ.get("SECRET_KEY", "docx-translator-secret-key-change-me")

# Порт веб-сервера
PORT = int(os.environ.get("PORT", 5000))

# Режим отладки Flask (включает auto-reload и подробные ошибки)
FLASK_DEBUG = os.environ.get("FLASK_DEBUG", "0") == "1"

# ---------------------------------------------------------------------------
# Логирование
# ---------------------------------------------------------------------------

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("docx_translator")
